from flask import Flask, request #This line is use to import the flask class from the flask module.

app = Flask(__name__) #This line creates an instance of the Flask class. The __name__ variable is a special variable in Python that holds the name of the current module. When you run a Python script, __name__ is set to "__main__". This allows Flask to know where to look for resources such as templates and static files.

@app.route("/") #This line is a decorator that tells Flask which URL should trigger the function that follows it. In this case, the "/" URL will trigger the home() function.
def home():
    return "<h1>Hello Flask</h1>"

@app.route("/about")
def about():
    return "About page"


@app.route("/submit", methods=["POST", "GET"])
def submit():
    if request.method=="POST":
        return "You are using POST method"
    else:
        return "You are using GET method"

if __name__ == "__main__":
    app.run(debug=True) #This line runs the Flask application. The debug=True argument enables debug mode, which provides helpful error messages and automatically reloads the server when code changes are made.

